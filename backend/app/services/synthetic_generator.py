def generate_synthetic_telemetry(
    db: Session,
    *,
    scenario: str = "all_scenarios",
    auto_correlate: bool = True,
) -> dict[str, Any]:
    """Generate, ingest, detect, and optionally correlate synthetic security events."""
    ensure_initial_seed_data(db)
    valid_scenarios = {s["scenario_id"] for s in SYNTHETIC_SCENARIOS_CATALOG} | {
        "all_scenarios"
    }
    norm_scenario = (scenario or "all_scenarios").strip().lower()
    if norm_scenario not in valid_scenarios:
        raise ValueError(
            f"Unsupported synthetic scenario '{scenario}'. Allowed: {sorted(valid_scenarios)}"
        )

    now = datetime.now(timezone.utc)
    run_tag = f"SIM-{uuid.uuid4().hex[:6].upper()}"
    records = _build_scenario_records(norm_scenario, now, run_tag)

    ingestion_result = ingest_records(
        db,
        records,
        source_format="synthetic_generator",
        default_is_synthetic=True,
    )

    correlation_summary: dict[str, Any] | None = None
    if auto_correlate:
        correlation_summary = correlate_security_events(db, window_minutes=60)

    return {
        "scenario": norm_scenario,
        "simulation_run_tag": run_tag,
        "synthetic_marker": "[SYNTHETIC SIMULATION]",
        "disclaimer": (
            "All generated events are synthetic simulation records for defensive evaluation "
            "and do not represent real-world cyberattacks."
        ),
        "ingestion_summary": ingestion_result,
        "correlation_summary": {
            "clusters_count": correlation_summary["clusters_count"]
            if correlation_summary
            else 0,
            "clusters": correlation_summary["clusters"]
            if correlation_summary
            else [],
        },
    }
